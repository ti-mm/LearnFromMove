def _json_exact_equal(left: object, right: object) -> bool:
    """Compare JSON values without treating integers and floats as interchangeable."""

    if isinstance(left, dict):
        if not isinstance(right, dict) or left.keys() != right.keys():
            return False
        return all(_json_exact_equal(left[key], right[key]) for key in left)
    if isinstance(left, list):
        return isinstance(right, list) and len(left) == len(right) and all(
            _json_exact_equal(left_item, right_item)
            for left_item, right_item in zip(left, right, strict=True)
        )
    return type(left) is type(right) and left == right


def _validate_teacher_result(
    result: TeacherResult,
    *,
    expected_action: Mapping[str, object],
) -> None:
    if not _json_exact_equal(result.action, dict(expected_action)):
        raise TeacherOutputError(
            "provider returned action does not match the immutable expected action: "
            f"expected={_compact_json(expected_action)} returned={_compact_json(result.action)}"
        )
    quality_errors = _think_quality_errors(result.think)
    if quality_errors:
        raise TeacherOutputError("; ".join(quality_errors))


class OpenAICompatibleTeacher:
    """OpenAI-compatible multimodal teacher with hard output validation."""

    def __init__(
        self,
        *,
        base_url: str,
        api_key: str,
        settings: GenerationSettings,
        timeout: float = 180.0,
        retries: int = 3,
        retry_base_delay: float = 2.0,
        max_connections: int = 100,
        client: httpx.Client | None = None,
    ) -> None:
        if max_connections < 1:
            raise ValueError("max_connections must be at least one")
        normalized = base_url.rstrip("/")
        self.url = (
            normalized
            if normalized.endswith("/chat/completions")
            else normalized + "/chat/completions"
        )
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        self.settings = settings
        self.retries = retries
        self.retry_base_delay = retry_base_delay
        self.max_connections = max_connections
        self._client = client or httpx.Client(
            timeout=timeout,
            trust_env=False,
            limits=httpx.Limits(
                max_connections=max_connections,
                max_keepalive_connections=min(20, max_connections),
            ),
        )
        self._owns_client = client is None

    @property
    def identity(self) -> dict[str, object]:
        return {
            "backend": "openai_compatible_chat_completions",
            "base_url": self.base_url,
            **self.settings.fingerprint_payload(),
        }

    def close(self) -> None:
        if self._owns_client:
            self._client.close()

    def __enter__(self) -> OpenAICompatibleTeacher:
        return self

    def __exit__(self, *_exc: object) -> None:
        self.close()

    def generate(
        self,
        *,
        messages: list[dict[str, object]],
        expected_action: dict[str, object],
    ) -> TeacherResult:
        active_messages = copy.deepcopy(messages)
        last_error: Exception | None = None
        for attempt in range(1, self.retries + 2):
            started = time.time()
            raw_text = ""
            try:
                body: dict[str, object] = {
                    "model": self.settings.model,
                    "messages": active_messages,
                    "max_tokens": self.settings.max_tokens,
                    "temperature": self.settings.temperature,
                    "top_p": self.settings.top_p,
                    "chat_template_kwargs": {
                        "enable_thinking": self.settings.enable_thinking
                    },
                }
                if self.settings.thinking_budget is not None:
                    body["thinking_budget"] = self.settings.thinking_budget
                headers = {"Content-Type": "application/json"}
                if self.api_key:
                    headers["Authorization"] = f"Bearer {self.api_key}"
                response = self._client.post(self.url, headers=headers, json=body)
                if response.status_code != 200:
                    raise RuntimeError(
                        f"chat completion HTTP {response.status_code}: {response.text[:1000]}"
                    )
                data = response.json()
                choices = data.get("choices") if isinstance(data, dict) else None
                if not isinstance(choices, list) or not choices:
                    raise TeacherOutputError("provider response has no choices")
                choice = choices[0] if isinstance(choices[0], dict) else {}
                message = choice.get("message") if isinstance(choice.get("message"), dict) else {}
                finish_reason = choice.get("finish_reason")
                content = message.get("content")
                reasoning = message.get("reasoning_content")
                if not isinstance(reasoning, str) or not reasoning.strip():
                    reasoning = message.get("reasoning")
                raw_text = content.strip() if isinstance(content, str) else ""
                reasoning_text = reasoning.strip() if isinstance(reasoning, str) else ""
                if finish_reason == "length":
                    detail = " after producing private reasoning" if reasoning_text else ""
                    raise TeacherOutputError(f"provider stopped at max_tokens{detail}")
                if not raw_text:
                    detail = (
                        "; private reasoning was present but no final JSON was returned"
                        if reasoning_text
                        else ""
                    )
                    raise TeacherOutputError(
                        f"provider returned no final content JSON{detail}"
                    )
                think, action = _extract_teacher_payload(raw_text)
                result = TeacherResult(
                    think=think,
                    action=action,
                    raw_text=raw_text,
                    finish_reason=(
                        str(finish_reason) if finish_reason is not None else None
                    ),
                    usage=(
                        dict(data.get("usage"))
                        if isinstance(data, dict) and isinstance(data.get("usage"), dict)
                        else {}
                    ),
                    attempt=attempt,
                    elapsed_seconds=time.time() - started,
                )
                _validate_teacher_result(result, expected_action=expected_action)
                return result
            except Exception as exc:
                last_error = exc
                if attempt > self.retries:
                    break
                correction = (
                    "The previous response was rejected: "
                    f"{exc}. Return one strict JSON object with a nonempty English visual "
                    "think in the final message content, even when private reasoning is "
                    "enabled, and copy this exact action object without changing any field "
                    f"or numeric value: {_compact_json(expected_action)}"
                )
                if raw_text:
                    active_messages.extend(
                        [
                            {"role": "assistant", "content": raw_text},
                            {"role": "user", "content": correction},
                        ]
                    )
                else:
                    active_messages.append({"role": "user", "content": correction})
                time.sleep(self.retry_base_delay * (2 ** (attempt - 1)))
        assert last_error is not None
        if isinstance(last_error, TeacherOutputError):
            raise last_error
        raise RuntimeError(f"teacher request failed after retries: {last_error}") from last_error


def request_fingerprint(
    *,
    source_manifest_sha256: str,
    record_id: str,
    task: str,
    variant: str,
    action_index: int,
    total_actions: int,
    instruction: str,
    image_paths: list[Path],
    previous_responses: list[str],
    expected_action: Mapping[str, object],
    button_state: str,
    teacher_identity: Mapping[str, object],
    expected_piece_visual: tuple[str, str] | None = None,
    image_sha256: Callable[[Path], str] = _sha256_file,
) -> str:
    rendered_prompt = SYSTEM_PROMPT + "\n" + _teacher_user_text(
        task=task,
        variant=variant,
        instruction=instruction,
        current_action=dict(expected_action),
        action_index=action_index,
        total_actions=total_actions,
        button_state=button_state,
    )
    payload = {
        "prompt_version": PROMPT_VERSION,
        "rendered_prompt_sha256": _sha256_bytes(rendered_prompt.encode("utf-8")),
        "previous_response_template_sha256": _sha256_bytes(
            PREVIOUS_RESPONSE_TEMPLATE.encode("utf-8")
        ),
        "message_interleaving": "image_then_corresponding_prior_response_then_instruction",
        "teacher_history_contract": TEACHER_HISTORY_CONTRACT,
        "source_manifest_sha256": source_manifest_sha256,
        "record_id": record_id,
        "task": task,
        "variant": variant,
        "action_index": action_index,
        "total_actions": total_actions,
        "instruction": instruction,
        "target_label": (
            extract_ten_choice_target_label(instruction)
            if task == "ten_choice"
            else None
        ),
        "images": [
            {"path": str(path), "sha256": image_sha256(path)} for path in image_paths
        ],
        "previous_responses": previous_responses,
        "expected_action": dict(expected_action),
        "button_state": button_state,
        "expected_piece_visual": expected_piece_visual,
        "teacher": dict(teacher_identity),
    }
    encoded = json.dumps(payload, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return _sha256_bytes(encoded.encode("utf-8"))


def _cache_path(
    cache_dir: Path,
    *,
    task: str,
    variant: str,
    record_index: int,
    action_index: int,
    fingerprint: str,
) -> Path:
    return (
        cache_dir
        / variant
        / task
        / f"{record_index:06d}"
        / f"{action_index:02d}_{fingerprint}.json"
    )


def _load_cache(
    path: Path,
    *,
    fingerprint: str,
    expected_action: Mapping[str, object],
) -> TeacherResult | None:
    if not path.is_file():
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        if payload.get("request_fingerprint") != fingerprint:
            return None
        result = TeacherResult(
            think=str(payload["think"]),
            action=dict(payload["action"]),
            raw_text=str(payload.get("raw_text") or ""),
            finish_reason=(
                str(payload["finish_reason"])
                if payload.get("finish_reason") is not None
                else None
            ),
            usage=dict(payload.get("usage") or {}),
            attempt=int(payload.get("attempt") or 0),
            elapsed_seconds=float(payload.get("elapsed_seconds") or 0.0),
        )
        _validate_teacher_result(result, expected_action=expected_action)
    except (KeyError, TypeError, ValueError, json.JSONDecodeError):
        return None
    return result


def _write_cache(path: Path, *, fingerprint: str, result: TeacherResult) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "request_fingerprint": fingerprint,
        "think": result.think,
        "action": result.action,
        "raw_text": result.raw_text,
        "finish_reason": result.finish_reason,
        "usage": result.usage,
        "attempt": result.attempt,
        "elapsed_seconds": result.elapsed_seconds,
    }
    temporary = path.with_suffix(f".{os.getpid()}.tmp")
    temporary.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    temporary.replace(path)


def _atomic_action(record: Mapping[str, object]) -> dict[str, object]:
    kind = record.get("action")
    if kind == "click":
        x_value = record.get("x")
        y_value = record.get("y")
        if not isinstance(x_value, (int, float)) or not isinstance(y_value, (int, float)):
            raise DatasetContractError("atomic click requires numeric x and y")
        return {"kind": "click", "points": [[x_value, y_value]]}
    if kind == "drag":
        values = [
            record.get("start_x"),
            record.get("start_y"),
            record.get("end_x"),
            record.get("end_y"),
        ]
        if not all(isinstance(value, (int, float)) for value in values):
            raise DatasetContractError("atomic drag requires numeric start/end coordinates")
        return {
            "kind": "drag",
            "points": [[values[0], values[1]], [values[2], values[3]]],
        }
    raise DatasetContractError(f"unsupported atomic action: {kind!r}")


def _step_action(step: Mapping[str, object]) -> dict[str, object]:
    nested = step.get("action")
    if isinstance(nested, dict):
        return dict(nested)
    kind = step.get("kind")
    if kind == "move_to":
        x_value = step.get("x")
        y_value = step.get("y")
        if not isinstance(x_value, (int, float)) or not isinstance(y_value, (int, float)):
            raise DatasetContractError("move_to requires numeric x and y")
        return {"kind": "move_to", "x": x_value, "y": y_value}
    if kind in {"mouse_down", "mouse_up", "left_click"}:
        return {"kind": str(kind)}
    raise DatasetContractError(f"unsupported primitive action: {kind!r}")


def _update_button_state(action: Mapping[str, object], current: str) -> str:
    if action.get("kind") == "mouse_down":
        return "down"
    if action.get("kind") == "mouse_up":
        return "up"
    return current


def _retained_teacher_context(
    image_history: list[Path],
    previous_responses: list[str],
    *,
    image_history_max: int,
) -> tuple[list[Path], list[str]]:
    retained_images = image_history[-image_history_max:]
    prior_count = max(0, len(retained_images) - 1)
    retained_responses = previous_responses[-prior_count:] if prior_count else []
    return retained_images, retained_responses


def _response_hash(response: object) -> str | None:
    if not isinstance(response, str) or not response:
        return None
    return _sha256_bytes(response.encode("utf-8"))


def _mark_teacher_provenance(
    metadata: object,
    *,
    old_response: object,
    action_index: int,
    fingerprint: str,
    cache_hit: bool,
    result: TeacherResult,
    teacher: TeacherBackend,
) -> dict[str, object]:
    output = dict(metadata) if isinstance(metadata, dict) else {}
    ablation = dict(output.get("ablation")) if isinstance(output.get("ablation"), dict) else {}
    previous_policy = ablation.get("response_policy")
    if isinstance(previous_policy, str) and previous_policy != ALL_ACTION_RESPONSE_POLICY:
        ablation["pre_teacher_response_policy"] = previous_policy
    ablation["response_policy"] = ALL_ACTION_RESPONSE_POLICY
    output["ablation"] = ablation
    output["teacher_think_metadata"] = {
        "prompt_version": PROMPT_VERSION,
        "history_contract": TEACHER_HISTORY_CONTRACT,
        "action_index": action_index,
        "request_fingerprint": fingerprint,
        "cache_hit": cache_hit,
        "model": teacher.settings.model,
        "generation": teacher.settings.fingerprint_payload(),
        "finish_reason": result.finish_reason,
        "attempt": result.attempt,
        "replaced_response_sha256": _response_hash(old_response),
    }
    return output


def _generate_action_response(
    *,
    record_id: str,
    task: str,
    variant: str,
    record_index: int,
    action_index: int,
    total_actions: int,
    instruction: str,
    image_history: list[Path],
    previous_responses: list[str],
    expected_action: dict[str, object],
    button_state: str,
    source_manifest_sha256: str,
    cache_dir: Path,
    teacher: TeacherBackend,
    image_history_max: int,
    image_cache: _RecordImageCache,
    expected_piece_visual: tuple[str, str] | None,
) -> tuple[TeacherResult, bool, str, int, int]:
    retained_images, retained_responses = _retained_teacher_context(
        image_history,
        previous_responses,
        image_history_max=image_history_max,
    )
    fingerprint = request_fingerprint(
        source_manifest_sha256=source_manifest_sha256,
        record_id=record_id,
        task=task,
        variant=variant,
        action_index=action_index,
        total_actions=total_actions,
        instruction=instruction,
        image_paths=retained_images,
        previous_responses=retained_responses,
        expected_action=expected_action,
        button_state=button_state,
        teacher_identity=teacher.identity,
        expected_piece_visual=expected_piece_visual,
        image_sha256=image_cache.sha256,
    )
    cache_path = _cache_path(
        cache_dir,
        task=task,
        variant=variant,
        record_index=record_index,
        action_index=action_index,
        fingerprint=fingerprint,
    )
    result = _load_cache(
        cache_path,
        fingerprint=fingerprint,
        expected_action=expected_action,
    )
    cache_hit = result is not None
    if result is None:
        messages = build_teacher_messages(
            task=task,
            variant=variant,
            instruction=instruction,
            image_history=image_history,
            previous_responses=previous_responses,
            current_action=expected_action,
            action_index=action_index,
            total_actions=total_actions,
            button_state=button_state,
            image_history_max=image_history_max,
            image_encoder=image_cache.encoded,
        )
        result = teacher.generate(
            messages=messages,
            expected_action=expected_action,
        )
        _validate_teacher_result(result, expected_action=expected_action)
        _write_cache(cache_path, fingerprint=fingerprint, result=result)
    return result, cache_hit, fingerprint, len(retained_images), len(retained_responses)


