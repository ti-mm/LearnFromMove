def annotate_record(
    record: Mapping[str, object],
    *,
    task: str,
    variant: str,
    record_index: int,
    source_manifest_sha256: str,
    cache_dir: Path,
    teacher: TeacherBackend,
    image_history_max: int = IMAGE_HISTORY_MAX,
    manifest_path: Path | None = None,
    expected_piece_visual_override: tuple[str, str] | None = None,
) -> tuple[dict[str, object], list[dict[str, object]]]:
    """Deep-copy one record and regenerate every action response."""

    if task not in TASKS:
        raise DatasetContractError(f"unsupported task: {task!r}")
    if variant not in VARIANTS:
        raise DatasetContractError(f"unsupported variant: {variant!r}")
    if image_history_max < 1:
        raise ValueError("image_history_max must be at least one")

    output = copy.deepcopy(dict(record))
    record_id = str(output.get("id") or "")
    if not record_id:
        raise DatasetContractError("record is missing id")
    instruction = str(output.get("instruction") or "")
    target_label = (
        extract_ten_choice_target_label(instruction) if task == "ten_choice" else None
    )
    if task == "ten_choice" and target_label is None:
        raise DatasetContractError(f"{record_id}: could not extract ten-choice target label")
    image_cache = _RecordImageCache()

    if variant == ATOMIC_VARIANT:
        action = _atomic_action(output)
        expected_kind = "click" if task == "ten_choice" else "drag"
        if action["kind"] != expected_kind:
            raise DatasetContractError(
                f"{record_id}: {task} atomic action must be {expected_kind}"
            )
        image_path = _resolve_image_path(output.get("image_path"), manifest_path=manifest_path)
        expected_piece_visual = expected_piece_visual_override
        if task == "third_person_drag" and expected_piece_visual is None:
            expected_piece_visual = _third_person_expected_visual(
                record_id=record_id,
                image_path=image_path,
            )
        old_response = output.get("assistant_response")
        result, cache_hit, fingerprint, image_count, prior_count = _generate_action_response(
            record_id=record_id,
            task=task,
            variant=variant,
            record_index=record_index,
            action_index=1,
            total_actions=1,
            instruction=instruction,
            image_history=[image_path],
            previous_responses=[],
            expected_action=action,
            button_state="up",
            source_manifest_sha256=source_manifest_sha256,
            cache_dir=cache_dir,
            teacher=teacher,
            image_history_max=image_history_max,
            image_cache=image_cache,
            expected_piece_visual=expected_piece_visual,
        )
        response = build_canonical_assistant_response(thought=result.think, action=action)
        set_canonical_assistant_response(output, response)
        output["metadata"] = _mark_teacher_provenance(
            output.get("metadata"),
            old_response=old_response,
            action_index=1,
            fingerprint=fingerprint,
            cache_hit=cache_hit,
            result=result,
            teacher=teacher,
        )
        audit = _audit_row(
            record_id=record_id,
            task=task,
            variant=variant,
            record_index=record_index,
            action_index=1,
            total_actions=1,
            action=action,
            old_response=old_response,
            new_response=response,
            result=result,
            cache_hit=cache_hit,
            fingerprint=fingerprint,
            image_count=image_count,
            prior_response_count=prior_count,
            button_state="up",
            instruction=instruction,
            expected_piece_visual=expected_piece_visual,
            target_label=target_label,
        )
        return output, [audit]

    raw_steps = output.get("steps")
    if not isinstance(raw_steps, list) or not raw_steps:
        raise DatasetContractError(f"{record_id}: single-move record is missing steps")
    steps = [step for step in raw_steps if isinstance(step, dict)]
    if len(steps) != len(raw_steps):
        raise DatasetContractError(f"{record_id}: every step must be an object")
    total_actions = sum(step.get("type") == "action" for step in steps)
    if total_actions < 1:
        raise DatasetContractError(f"{record_id}: trajectory has no actions")

    image_history: list[Path] = []
    previous_responses: list[str] = []
    button_state = "up"
    action_index = 0
    audit_rows: list[dict[str, object]] = []
    expected_piece_visual = expected_piece_visual_override
    for step in steps:
        step_type = step.get("type")
        if step_type == "observation":
            image_history.append(
                _resolve_image_path(
                    step.get("image_path") or step.get("observation_image"),
                    manifest_path=manifest_path,
                )
            )
            continue
        if step_type != "action":
            raise DatasetContractError(f"{record_id}: unsupported step type {step_type!r}")
        if not image_history:
            raise DatasetContractError(f"{record_id}: action has no pre-action observation")

        action_index += 1
        if len(image_history) != action_index:
            raise DatasetContractError(
                f"{record_id}: action {action_index} expected {action_index} causal "
                f"observations, got {len(image_history)}"
            )
        action = _step_action(step)
        if task == "third_person_drag" and expected_piece_visual is None:
            expected_piece_visual = _third_person_expected_visual(
                record_id=record_id,
                image_path=image_history[0],
            )
        old_response = step.get("assistant_response")
        state_before = button_state
        result, cache_hit, fingerprint, image_count, prior_count = _generate_action_response(
            record_id=record_id,
            task=task,
            variant=variant,
            record_index=record_index,
            action_index=action_index,
            total_actions=total_actions,
            instruction=instruction,
            image_history=image_history,
            previous_responses=previous_responses,
            expected_action=action,
            button_state=state_before,
            source_manifest_sha256=source_manifest_sha256,
            cache_dir=cache_dir,
            teacher=teacher,
            image_history_max=image_history_max,
            image_cache=image_cache,
            expected_piece_visual=expected_piece_visual,
        )
        response = build_canonical_assistant_response(thought=result.think, action=action)
        set_canonical_assistant_response(step, response)
        step["metadata"] = _mark_teacher_provenance(
            step.get("metadata"),
            old_response=old_response,
            action_index=action_index,
            fingerprint=fingerprint,
            cache_hit=cache_hit,
            result=result,
            teacher=teacher,
        )
        audit_rows.append(
            _audit_row(
                record_id=record_id,
                task=task,
                variant=variant,
                record_index=record_index,
                action_index=action_index,
                total_actions=total_actions,
                action=action,
                old_response=old_response,
                new_response=response,
                result=result,
                cache_hit=cache_hit,
                fingerprint=fingerprint,
                image_count=image_count,
                prior_response_count=prior_count,
                button_state=state_before,
                instruction=instruction,
                expected_piece_visual=expected_piece_visual,
                target_label=target_label,
            )
        )
        previous_responses.append(response)
        button_state = _update_button_state(action, button_state)

    if action_index != total_actions:
        raise DatasetContractError(
            f"{record_id}: annotated {action_index} of {total_actions} actions"
        )
    record_metadata = (
        dict(output.get("metadata")) if isinstance(output.get("metadata"), dict) else {}
    )
    record_metadata["teacher_think_all_actions"] = {
        "prompt_version": PROMPT_VERSION,
        "history_contract": TEACHER_HISTORY_CONTRACT,
        "actions": total_actions,
        "model": teacher.settings.model,
    }
    output["metadata"] = record_metadata
    return output, audit_rows


def _record_actions(record: Mapping[str, object], *, variant: str) -> list[dict[str, object]]:
    if variant == ATOMIC_VARIANT:
        return [_atomic_action(record)]
    steps = record.get("steps")
    if not isinstance(steps, list):
        raise DatasetContractError("single-move record has no steps")
    return [
        _step_action(step)
        for step in steps
        if isinstance(step, dict) and step.get("type") == "action"
    ]


def _pre_action_images(
    record: Mapping[str, object],
    *,
    variant: str,
    manifest_path: Path,
) -> list[Path]:
    if variant == ATOMIC_VARIANT:
        return [
            _normalized_image_path(record.get("image_path"), manifest_path=manifest_path)
        ]
    steps = record.get("steps")
    if not isinstance(steps, list):
        raise DatasetContractError("single-move record has no steps")
    current_image: Path | None = None
    images: list[Path] = []
    for step in steps:
        if not isinstance(step, dict):
            raise DatasetContractError("single-move step is not an object")
        if step.get("type") == "observation":
            current_image = _normalized_image_path(
                step.get("image_path") or step.get("observation_image"),
                manifest_path=manifest_path,
            )
        elif step.get("type") == "action":
            if current_image is None:
                raise DatasetContractError("action has no pre-action observation")
            images.append(current_image)
    return images


def _instance_context_snapshot(
    records: list[dict[str, object]],
    *,
    task: str,
    variant: str,
    manifest_path: Path,
) -> tuple[str | None, int, dict[str, tuple[str, str]]]:
    if task not in {"ten_choice", "third_person_drag"}:
        return None, 0, {}
    entries: list[dict[str, object]] = []
    expected_visuals: dict[str, tuple[str, str]] = {}
    missing = 0
    for record in records:
        record_id = str(record.get("id") or "")
        if task == "ten_choice":
            target_label = extract_ten_choice_target_label(
                str(record.get("instruction") or "")
            )
            if target_label is None:
                missing += 1
            entries.append({"record_id": record_id, "target_label": target_label})
            continue

        decision_images = _pre_action_images(
            record,
            variant=variant,
            manifest_path=manifest_path,
        )
        context = (
            _third_person_visual_context(
                record_id=record_id,
                image_path=decision_images[0],
            )
            if decision_images
            else None
        )
        if context is None:
            missing += 1
            entries.append(
                {
                    "record_id": record_id,
                    "image_path": str(decision_images[0]) if decision_images else None,
                    "missing": True,
                }
            )
            continue
        expected_visuals[record_id] = (context["color_name"], context["shape"])
        entries.append({"record_id": record_id, **context})
    encoded = json.dumps(
        entries,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return _sha256_bytes(encoded), missing, expected_visuals


def annotate_manifest(
    manifest_path: Path,
    *,
    task: str,
    variant: str,
    cache_dir: Path,
    teacher: TeacherBackend,
    workers: int = 16,
    image_history_max: int = IMAGE_HISTORY_MAX,
    progress_every: int = 0,
    expected_instance_context_sha256: str | None = None,
    require_instance_context: bool = False,
) -> tuple[list[dict[str, object]], list[dict[str, object]], dict[str, object]]:
    source_sha_before_read = _sha256_file(manifest_path)
    records = _read_jsonl(manifest_path)
    source_sha = _sha256_file(manifest_path)
    if source_sha != source_sha_before_read:
        raise DatasetContractError(f"source manifest changed while reading: {manifest_path}")
    instance_context_sha, missing_instance_contexts, expected_visuals = (
        _instance_context_snapshot(
            records,
            task=task,
            variant=variant,
            manifest_path=manifest_path,
        )
    )
    if (
        expected_instance_context_sha256 is not None
        and instance_context_sha != expected_instance_context_sha256
    ):
        raise DatasetContractError(
            f"instance context changed after planning: {variant}/{task}"
        )
    if require_instance_context and missing_instance_contexts:
        raise DatasetContractError(
            f"{variant}/{task}: missing {missing_instance_contexts} formal instance contexts"
        )
    outputs: list[dict[str, object] | None] = [None] * len(records)
    audits: list[list[dict[str, object]] | None] = [None] * len(records)

    def process(index: int) -> tuple[int, dict[str, object], list[dict[str, object]]]:
        output, rows = annotate_record(
            records[index],
            task=task,
            variant=variant,
            record_index=index,
            source_manifest_sha256=source_sha,
            cache_dir=cache_dir,
            teacher=teacher,
            image_history_max=image_history_max,
            manifest_path=manifest_path,
            expected_piece_visual_override=expected_visuals.get(
                str(records[index].get("id") or "")
            ),
        )
        if _record_actions(output, variant=variant) != _record_actions(
            records[index], variant=variant
        ):
            raise DatasetContractError(
                f"{records[index].get('id')}: action payload changed during Think generation"
            )
        return index, output, rows

    if workers < 1:
        raise ValueError("workers must be at least one")
    completed = 0

    def report_progress() -> None:
        if progress_every > 0 and (
            completed % progress_every == 0 or completed == len(records)
        ):
            print(
                f"[{variant}/{task}] completed {completed}/{len(records)} records",
                file=sys.stderr,
                flush=True,
            )

    if workers == 1:
        for index in range(len(records)):
            _, outputs[index], audits[index] = process(index)
            completed += 1
            report_progress()
    else:
        with ThreadPoolExecutor(max_workers=workers) as executor:
            futures = {executor.submit(process, index): index for index in range(len(records))}
            try:
                for future in as_completed(futures):
                    index, output, rows = future.result()
                    outputs[index] = output
                    audits[index] = rows
                    completed += 1
                    report_progress()
            except Exception:
                for future in futures:
                    future.cancel()
                raise

    if any(record is None for record in outputs) or any(rows is None for rows in audits):
        raise RuntimeError("annotation completed with missing record results")
    completed_outputs = [record for record in outputs if record is not None]
    audit_rows = [row for rows in audits if rows is not None for row in rows]
    expected_actions = sum(len(_record_actions(record, variant=variant)) for record in records)
    if len(audit_rows) != expected_actions:
        raise DatasetContractError(
            f"{task}/{variant}: accepted {len(audit_rows)} of {expected_actions} actions"
        )
    if not all(row.get("action_match") is True for row in audit_rows):
        raise DatasetContractError(f"{task}/{variant}: audit contains action mismatch")
    final_context_sha, final_missing_contexts, _final_visuals = _instance_context_snapshot(
        records,
        task=task,
        variant=variant,
        manifest_path=manifest_path,
    )
    if (
        final_context_sha != instance_context_sha
        or final_missing_contexts != missing_instance_contexts
    ):
        raise DatasetContractError(
            f"instance context changed during generation: {variant}/{task}"
        )

    stats = {
        "records": len(records),
        "actions": expected_actions,
        "accepted": len(audit_rows),
        "cache_hits": sum(bool(row["cache_hit"]) for row in audit_rows),
        "provider_requests": sum(not bool(row["cache_hit"]) for row in audit_rows),
        "provider_attempts": sum(
            int(row["provider_attempt"]) for row in audit_rows if not bool(row["cache_hit"])
        ),
        "soft_quality_warning_actions": sum(
            bool(row["soft_quality_warnings"]) for row in audit_rows
        ),
        "soft_quality_warnings": sum(
            len(row["soft_quality_warnings"]) for row in audit_rows
        ),
        "source_manifest": str(manifest_path.resolve()),
        "source_manifest_sha256": source_sha,
        "instance_context_sha256": instance_context_sha,
        "missing_instance_contexts": missing_instance_contexts,
    }
    return completed_outputs, audit_rows, stats


def plan_dataset(input_root: Path) -> dict[str, object]:
    """Read the eight manifests and report the exact all-action request plan."""

    input_root = input_root.resolve()
    variants: dict[str, object] = {}
    planned_action_counts: dict[tuple[str, str], int] = {}
    planned_record_counts: dict[tuple[str, str], int] = {}
    planned_manifest_sha256: dict[tuple[str, str], str] = {}
    ordered_ids: dict[tuple[str, str], list[str]] = {}
    instance_context_digests: dict[tuple[str, str], str | None] = {}
    unique_images: set[Path] = set()
    missing_images: set[Path] = set()
    missing_third_person_identity_metadata = 0
    missing_ten_choice_target_labels = 0
    total_image_attachments = 0
    total_records = 0
    total_actions = 0
    for variant in VARIANTS:
        task_counts: dict[str, object] = {}
        variant_records = 0
        variant_actions = 0
        for task in TASKS:
            manifest = input_root / variant / task / "train.jsonl"
            records = _read_jsonl(manifest)
            record_ids = [str(record.get("id") or "") for record in records]
            if any(not record_id for record_id in record_ids):
                raise DatasetContractError(f"{manifest}: record without id")
            if len(set(record_ids)) != len(record_ids):
                raise DatasetContractError(f"{manifest}: duplicate record id")
            instance_context_sha, missing_contexts, expected_visuals = (
                _instance_context_snapshot(
                    records,
                    task=task,
                    variant=variant,
                    manifest_path=manifest,
                )
            )
            instance_context_digests[(variant, task)] = instance_context_sha
            if task == "ten_choice":
                missing_ten_choice_target_labels += missing_contexts
            if task == "third_person_drag":
                missing_third_person_identity_metadata += missing_contexts
            actions = sum(len(_record_actions(record, variant=variant)) for record in records)
            task_decision_images = 0
            task_attachments = 0
            task_identity_metadata_records = 0
            for record in records:
                decision_images = _pre_action_images(
                    record,
                    variant=variant,
                    manifest_path=manifest,
                )
                record_actions = len(_record_actions(record, variant=variant))
                if len(decision_images) != record_actions:
                    raise DatasetContractError(
                        f"{manifest}: record {record.get('id')} has {record_actions} actions "
                        f"but {len(decision_images)} pre-action images"
                    )
                if not decision_images:
                    raise DatasetContractError(
                        f"{manifest}: record {record.get('id')} has no action observation"
                    )
                if task == "third_person_drag" and str(record.get("id") or "") in expected_visuals:
                    task_identity_metadata_records += 1
                task_decision_images += len(decision_images)
                task_attachments += sum(
                    min(action_index, IMAGE_HISTORY_MAX)
                    for action_index in range(1, len(decision_images) + 1)
                )
                unique_images.update(decision_images)
                missing_images.update(path for path in decision_images if not path.is_file())
            ordered_id_sha = _sha256_bytes(("\n".join(record_ids) + "\n").encode("utf-8"))
            task_counts[task] = {
                "records": len(records),
                "actions": actions,
                "ordered_ids_sha256": ordered_id_sha,
                "manifest_sha256": _sha256_file(manifest),
                "instance_context_sha256": instance_context_sha,
                "missing_instance_contexts": missing_contexts,
                "decision_images": task_decision_images,
                "teacher_image_attachments": task_attachments,
                "third_person_identity_metadata_records": (
                    task_identity_metadata_records
                    if task == "third_person_drag"
                    else None
                ),
            }
            planned_action_counts[(variant, task)] = actions
            planned_record_counts[(variant, task)] = len(records)
            planned_manifest_sha256[(variant, task)] = str(
                task_counts[task]["manifest_sha256"]
            )
            ordered_ids[(variant, task)] = record_ids
            total_image_attachments += task_attachments
            variant_records += len(records)
            variant_actions += actions
        variants[variant] = {
            "records": variant_records,
            "actions": variant_actions,
            "tasks": task_counts,
        }
        total_records += variant_records
        total_actions += variant_actions
    formal_counts_match = all(
        planned_action_counts[(variant, task)] == FORMAL_ACTION_COUNTS[variant][task]
        and planned_record_counts[(variant, task)] == FORMAL_RECORD_COUNTS[task]
        for variant in VARIANTS
        for task in TASKS
    )
    matched_ordered_ids = all(
        ordered_ids[(ATOMIC_VARIANT, task)] == ordered_ids[(SINGLE_MOVE_VARIANT, task)]
        for task in TASKS
    )
    formal_manifest_digests_match = all(
        planned_manifest_sha256[(variant, task)]
        == FORMAL_MANIFEST_SHA256[variant][task]
        for variant in VARIANTS
        for task in TASKS
    )
    matched_instance_contexts = all(
        instance_context_digests[(ATOMIC_VARIANT, task)]
        == instance_context_digests[(SINGLE_MOVE_VARIANT, task)]
        for task in ("ten_choice", "third_person_drag")
    )
    return {
        "schema": SCHEMA,
        "input_root": str(input_root),
        "response_policy": ALL_ACTION_RESPONSE_POLICY,
        "teacher_history_contract": TEACHER_HISTORY_CONTRACT,
        "records": total_records,
        "actions": total_actions,
        "formal_expected_actions": FORMAL_TOTAL_ACTIONS,
        "matched_ordered_ids": matched_ordered_ids,
        "matched_instance_contexts": matched_instance_contexts,
        "formal_manifest_digests_match": formal_manifest_digests_match,
        "formal_counts_match": (
            formal_counts_match
            and matched_ordered_ids
            and matched_instance_contexts
            and formal_manifest_digests_match
            and total_actions == FORMAL_TOTAL_ACTIONS
            and not missing_images
            and missing_third_person_identity_metadata == 0
            and missing_ten_choice_target_labels == 0
        ),
        "unique_pre_action_images": len(unique_images),
        "teacher_image_attachments": total_image_attachments,
        "missing_images": len(missing_images),
        "missing_third_person_identity_metadata": missing_third_person_identity_metadata,
        "missing_ten_choice_target_labels": missing_ten_choice_target_labels,
        "variants": variants,
    }


def _input_ready_provenance(input_root: Path) -> dict[str, object]:
    ready_path = input_root / "READY.json"
    summary_path = input_root / "summary.json"
    if not ready_path.is_file() or not summary_path.is_file():
        raise DatasetContractError("formal input root requires READY.json and summary.json")
    ready = json.loads(ready_path.read_text(encoding="utf-8"))
    if not isinstance(ready, dict) or ready.get("status") != "passed":
        raise DatasetContractError("formal input READY.json is not passed")
    if ready.get("schema") != SCHEMA:
        raise DatasetContractError("formal input READY.json has the wrong schema")
    summary_sha = _sha256_file(summary_path)
    if ready.get("summary_sha256") != summary_sha:
        raise DatasetContractError("formal input summary hash does not match READY.json")
    return {
        "ready": str(ready_path),
        "ready_sha256": _sha256_file(ready_path),
        "summary": str(summary_path),
        "summary_sha256": summary_sha,
    }


def _planned_task_stats(
    plan: Mapping[str, object], *, variant: str, task: str
) -> Mapping[str, object]:
    variants = plan.get("variants")
    if not isinstance(variants, dict):
        raise DatasetContractError("input plan is missing variants")
    variant_stats = variants.get(variant)
    if not isinstance(variant_stats, dict):
        raise DatasetContractError(f"input plan is missing variant {variant}")
    tasks = variant_stats.get("tasks")
    if not isinstance(tasks, dict):
        raise DatasetContractError(f"input plan is missing tasks for {variant}")
    task_stats = tasks.get(task)
    if not isinstance(task_stats, dict):
        raise DatasetContractError(f"input plan is missing task {variant}/{task}")
    return task_stats


def _copy_rejections(source_path: Path, output_path: Path) -> None:
    records = _read_jsonl(source_path) if source_path.is_file() else []
    write_jsonl(output_path, records)


def _combined_parquet(task_parquets: list[Path], output_path: Path) -> int:
    frames = [pd.read_parquet(path) for path in task_parquets]
    combined = pd.concat(frames, ignore_index=True)
    combined = combined.sample(frac=1.0, random_state=SHUFFLE_SEED).reset_index(drop=True)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    combined.to_parquet(output_path, index=False)
    return len(combined)


def annotate_dataset(
    *,
    input_root: Path,
    output_root: Path,
    teachers: Mapping[str, TeacherBackend],
    workers: int = 16,
    image_history_max: int = IMAGE_HISTORY_MAX,
    image_max_pixels: int = HD720_IMAGE_MAX_PIXELS,
    resume: bool = False,
    enforce_formal_counts: bool = True,
    progress_every: int = 100,
) -> dict[str, object]:
    """Regenerate all actions, rebuild task/combined Parquets, then write READY."""

    input_root = input_root.resolve()
    output_root = output_root.resolve()
    if input_root == output_root:
        raise ValueError("output_root must differ from input_root")
    if set(teachers) != set(TASKS):
        raise ValueError("teachers must specify exactly the four supported tasks")
    input_plan = plan_dataset(input_root)
    if enforce_formal_counts and input_plan["formal_counts_match"] is not True:
        raise DatasetContractError(
            "formal all-action plan does not match the required 67,320-action contract"
        )
    input_ready = _input_ready_provenance(input_root) if enforce_formal_counts else None
    if output_root.exists() and any(output_root.iterdir()) and not resume:
        raise FileExistsError(
            f"refusing to reuse nonempty output directory without --resume: {output_root}"
        )
    output_root.mkdir(parents=True, exist_ok=True)
    generated_at = datetime.now(timezone.utc).isoformat()
    ready_path = output_root / "READY.json"
    if ready_path.is_file():
        ready_path.unlink()
    running_path = output_root / "RUNNING.json"
    _write_json(
        running_path,
        {
            "status": "running",
            "schema": SCHEMA,
            "started_at_utc": generated_at,
            "input_root": str(input_root),
            "output_root": str(output_root),
            "actions": input_plan["actions"],
        },
    )
    cache_dir = output_root / "cache"
    all_stats: dict[str, dict[str, dict[str, object]]] = {
        variant: {} for variant in VARIANTS
    }
    task_parquets: dict[str, list[Path]] = {variant: [] for variant in VARIANTS}

    for variant in VARIANTS:
        for task in TASKS:
            source_dir = input_root / variant / task
            source_manifest = source_dir / "train.jsonl"
            if not source_manifest.is_file():
                raise FileNotFoundError(str(source_manifest))
            planned_task = _planned_task_stats(input_plan, variant=variant, task=task)
            planned_source_sha = str(planned_task["manifest_sha256"])
            if _sha256_file(source_manifest) != planned_source_sha:
                raise DatasetContractError(
                    f"source manifest changed after planning: {variant}/{task}"
                )
            records, audit_rows, stats = annotate_manifest(
                source_manifest,
                task=task,
                variant=variant,
                cache_dir=cache_dir,
                teacher=teachers[task],
                workers=workers,
                image_history_max=image_history_max,
                progress_every=progress_every,
                expected_instance_context_sha256=(
                    str(planned_task["instance_context_sha256"])
                    if planned_task["instance_context_sha256"] is not None
                    else None
                ),
                require_instance_context=enforce_formal_counts,
            )
            if (
                stats["source_manifest_sha256"] != planned_source_sha
                or stats["instance_context_sha256"]
                != planned_task["instance_context_sha256"]
                or int(stats["missing_instance_contexts"])
                != int(planned_task["missing_instance_contexts"])
                or int(stats["records"]) != int(planned_task["records"])
                or int(stats["actions"]) != int(planned_task["actions"])
            ):
                raise DatasetContractError(
                    f"annotated source no longer matches input plan: {variant}/{task}"
                )
            task_dir = output_root / variant / task
            output_manifest = task_dir / "train.jsonl"
            write_jsonl(output_manifest, records)
            write_jsonl(task_dir / "teacher_audit.jsonl", audit_rows)
            _copy_rejections(source_dir / "rejected.jsonl", task_dir / "rejected.jsonl")

            rows = build_verl_rows(
                output_manifest,
                task=task,
                variant=variant,
                image_history_max=image_history_max,
                image_max_pixels=image_max_pixels,
            )
            if len(rows) != int(stats["actions"]):
                raise DatasetContractError(
                    f"{task}/{variant}: Parquet rows {len(rows)} != actions {stats['actions']}"
                )
            parquet_path = task_dir / "train.parquet"
            pd.DataFrame(rows).to_parquet(parquet_path, index=False)
            task_parquets[variant].append(parquet_path)
            task_summary = {
                "status": "passed",
                "schema": SCHEMA,
                "prompt_version": PROMPT_VERSION,
                "teacher_history_contract": TEACHER_HISTORY_CONTRACT,
                "final_sft_history_contract": HISTORY_CONTRACT,
                "task": task,
                "variant": variant,
                "generated_at_utc": generated_at,
                "teacher": teachers[task].identity,
                **stats,
                "outputs": {
                    "manifest": str(output_manifest),
                    "manifest_sha256": _sha256_file(output_manifest),
                    "audit": str(task_dir / "teacher_audit.jsonl"),
                    "audit_sha256": _sha256_file(task_dir / "teacher_audit.jsonl"),
                    "parquet": str(parquet_path),
                    "parquet_sha256": _sha256_file(parquet_path),
                },
            }
            _write_json(task_dir / "summary.json", task_summary)
            all_stats[variant][task] = task_summary

    variant_summaries: dict[str, dict[str, object]] = {}
    for variant in VARIANTS:
        combined_path = output_root / variant / "train.parquet"
        combined_rows = _combined_parquet(task_parquets[variant], combined_path)
        expected_rows = sum(int(all_stats[variant][task]["actions"]) for task in TASKS)
        if combined_rows != expected_rows:
            raise DatasetContractError(
                f"{variant}: combined rows {combined_rows} != actions {expected_rows}"
            )
        variant_summary = {
            "status": "passed",
            "schema": SCHEMA,
            "variant": variant,
            "generated_at_utc": generated_at,
            "records": sum(int(all_stats[variant][task]["records"]) for task in TASKS),
            "actions": expected_rows,
            "accepted": sum(int(all_stats[variant][task]["accepted"]) for task in TASKS),
            "cache_hits": sum(int(all_stats[variant][task]["cache_hits"]) for task in TASKS),
            "provider_requests": sum(
                int(all_stats[variant][task]["provider_requests"]) for task in TASKS
            ),
            "task_action_counts": {
                task: int(all_stats[variant][task]["actions"]) for task in TASKS
            },
            "train_parquet": str(combined_path),
            "train_parquet_sha256": _sha256_file(combined_path),
            "shuffle_seed": SHUFFLE_SEED,
            "teacher_history_contract": TEACHER_HISTORY_CONTRACT,
            "final_sft_history_contract": HISTORY_CONTRACT,
        }
        _write_json(output_root / variant / "summary.json", variant_summary)
        variant_summaries[variant] = variant_summary

    total_actions = sum(
        int(variant_summaries[variant]["actions"]) for variant in VARIANTS
    )
    total_accepted = sum(
        int(variant_summaries[variant]["accepted"]) for variant in VARIANTS
    )
    if total_actions != total_accepted:
        raise DatasetContractError(
            f"all-action completion gate failed: accepted {total_accepted}/{total_actions}"
        )
    if total_actions != int(input_plan["actions"]):
        raise DatasetContractError(
            f"generated actions {total_actions} != planned actions {input_plan['actions']}"
        )
    for variant in VARIANTS:
        for task in TASKS:
            source_manifest = input_root / variant / task / "train.jsonl"
            planned_task = _planned_task_stats(input_plan, variant=variant, task=task)
            current_records = _read_jsonl(source_manifest)
            current_context_sha, current_missing_contexts, _current_visuals = (
                _instance_context_snapshot(
                    current_records,
                    task=task,
                    variant=variant,
                    manifest_path=source_manifest,
                )
            )
            if (
                _sha256_file(source_manifest) != planned_task["manifest_sha256"]
                or all_stats[variant][task]["source_manifest_sha256"]
                != planned_task["manifest_sha256"]
                or int(all_stats[variant][task]["records"])
                != int(planned_task["records"])
                or int(all_stats[variant][task]["actions"])
                != int(planned_task["actions"])
                or current_context_sha != planned_task["instance_context_sha256"]
                or current_missing_contexts != int(planned_task["missing_instance_contexts"])
            ):
                raise DatasetContractError(
                    f"source manifest changed during generation: {variant}/{task}"
                )
    if enforce_formal_counts:
        formal_parts_match = all(
            int(all_stats[variant][task]["records"]) == FORMAL_RECORD_COUNTS[task]
            and int(all_stats[variant][task]["actions"])
            == FORMAL_ACTION_COUNTS[variant][task]
            for variant in VARIANTS
            for task in TASKS
        )
        if total_actions != FORMAL_TOTAL_ACTIONS or not formal_parts_match:
            raise DatasetContractError(
                "final outputs do not match the required 67,320-action formal contract"
            )
    summary: dict[str, object] = {
        "status": "passed",
        "schema": SCHEMA,
        "generated_at_utc": generated_at,
        "input_root": str(input_root),
        "output_root": str(output_root),
        "prompt_version": PROMPT_VERSION,
        "response_policy": ALL_ACTION_RESPONSE_POLICY,
        "teacher_history_contract": TEACHER_HISTORY_CONTRACT,
        "final_sft_history_contract": HISTORY_CONTRACT,
        "image_history_max": image_history_max,
        "image_max_pixels": image_max_pixels,
        "actions": total_actions,
        "accepted": total_accepted,
        "all_actions_covered": total_actions == total_accepted,
        "formal_expected_actions": FORMAL_TOTAL_ACTIONS,
        "formal_counts_match": input_plan["formal_counts_match"],
        "input_plan": input_plan,
        "input_ready": input_ready,
        "tasks": {
            variant: {
                task: {
                    "teacher": all_stats[variant][task]["teacher"],
                    "source_manifest": all_stats[variant][task]["source_manifest"],
                    "source_manifest_sha256": all_stats[variant][task][
                        "source_manifest_sha256"
                    ],
                    "records": all_stats[variant][task]["records"],
                    "actions": all_stats[variant][task]["actions"],
                    "outputs": all_stats[variant][task]["outputs"],
                }
                for task in TASKS
            }
            for variant in VARIANTS
        },
        "variants": variant_summaries,
        "training_status": "not_started",
        "environment_evaluation_status": "not_started",
    }
    summary_path = output_root / "summary.json"
    _write_json(summary_path, summary)
    task_outputs = {
        variant: {
            task: {
                **all_stats[variant][task]["outputs"],
                "summary": str(output_root / variant / task / "summary.json"),
                "summary_sha256": _sha256_file(
                    output_root / variant / task / "summary.json"
                ),
            }
            for task in TASKS
        }
        for variant in VARIANTS
    }
    ready = {
        "status": "passed",
        "schema": SCHEMA,
        "readiness_scope": (
            "formal_all_action_teacher_thinks_and_training_inputs"
            if enforce_formal_counts
            else "development_nonformal_teacher_thinks_and_training_inputs"
        ),
        "formal_run": enforce_formal_counts,
        "formal_counts_match": input_plan["formal_counts_match"],
        "actions": total_actions,
        "accepted": total_accepted,
        "summary": str(summary_path),
        "summary_sha256": _sha256_file(summary_path),
        "variant_parquets": {
            variant: {
                "path": variant_summaries[variant]["train_parquet"],
                "sha256": variant_summaries[variant]["train_parquet_sha256"],
            }
            for variant in VARIANTS
        },
        "task_outputs": task_outputs,
    }
    _write_json_atomic(ready_path, ready)
    running_path.unlink()
    return summary


def _settings_from_mapping(payload: Mapping[str, object]) -> GenerationSettings:
    model_env = payload.get("model_env")
    model = (
        os.environ.get(str(model_env), "")
        if isinstance(model_env, str) and model_env
        else payload.get("model")
    )
    if not isinstance(model, str) or not model.strip():
        raise ValueError("teacher config requires a nonempty model")
    return GenerationSettings(
        model=model,
        max_tokens=int(payload.get("max_tokens", 512)),
        temperature=float(payload.get("temperature", 0.2)),
        top_p=float(payload.get("top_p", 0.9)),
        enable_thinking=bool(payload.get("enable_thinking", False)),
        thinking_budget=(
            int(payload["thinking_budget"])
            if payload.get("thinking_budget") is not None
            else None
        ),
    )


def _backend_from_mapping(
    payload: Mapping[str, object],
    *,
    timeout: float,
    retries: int,
    retry_base_delay: float,
    max_connections: int,
) -> OpenAICompatibleTeacher:
    base_url_env = payload.get("base_url_env")
    base_url = (
        os.environ.get(str(base_url_env), "")
        if isinstance(base_url_env, str) and base_url_env
        else payload.get("base_url")
    )
    if not isinstance(base_url, str) or not base_url.strip():
        raise ValueError("teacher config requires a nonempty base_url ending in /v1")
    api_key_env = str(payload.get("api_key_env") or "TEACHER_API_KEY")
    api_key = os.environ.get(api_key_env, "")
    return OpenAICompatibleTeacher(
        base_url=base_url,
        api_key=api_key,
        settings=_settings_from_mapping(payload),
        timeout=timeout,
        retries=retries,
        retry_base_delay=retry_base_delay,
        max_connections=max_connections,
    )


def _load_backends(args: argparse.Namespace) -> dict[str, OpenAICompatibleTeacher]:
    if args.teacher_config is not None:
        payload = json.loads(args.teacher_config.read_text(encoding="utf-8"))
        task_payloads = payload.get("tasks") if isinstance(payload, dict) else None
        if not isinstance(task_payloads, dict) or set(task_payloads) != set(TASKS):
            raise ValueError("teacher config must contain exactly four entries under tasks")
        return {
            task: _backend_from_mapping(
                task_payloads[task],
                timeout=args.timeout,
                retries=args.retries,
                retry_base_delay=args.retry_base_delay,
                max_connections=args.max_connections,
            )
            for task in TASKS
        }
    if not args.base_url or not args.model:
        raise ValueError("provide --teacher-config or both --base-url and --model")
    shared = {
        "base_url": args.base_url,
        "model": args.model,
        "api_key_env": args.api_key_env,
        "max_tokens": args.max_tokens,
        "temperature": args.temperature,
        "top_p": args.top_p,
        "enable_thinking": args.enable_thinking,
        "thinking_budget": args.thinking_budget,
    }
    return {
        task: _backend_from_mapping(
            shared,
            timeout=args.timeout,
            retries=args.retries,
            retry_base_delay=args.retry_base_delay,
            max_connections=args.max_connections,
        )
        for task in TASKS
    }


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-root", type=Path, default=None)
    parser.add_argument("--output-root", type=Path, default=None)
    parser.add_argument(
        "--teacher-config",
        type=Path,
        default=None,
        help=(
            "JSON with exactly four task configs under tasks; each entry needs base_url, "
            "model, and optionally base_url_env/model_env/api_key_env/generation settings."
        ),
    )
    parser.add_argument("--base-url", default=None, help="OpenAI-compatible base URL ending in /v1")
    parser.add_argument("--model", default=None)
    parser.add_argument("--api-key-env", default="TEACHER_API_KEY")
    parser.add_argument("--max-tokens", type=int, default=512)
    parser.add_argument("--temperature", type=float, default=0.2)
    parser.add_argument("--top-p", type=float, default=0.9)
    parser.add_argument("--enable-thinking", action="store_true")
    parser.add_argument("--thinking-budget", type=int, default=None)
    parser.add_argument("--workers", type=int, default=16)
    parser.add_argument(
        "--max-connections",
        type=int,
        default=None,
        help="HTTP connection-pool size; defaults to max(100, workers).",
    )
    parser.add_argument("--timeout", type=float, default=180.0)
    parser.add_argument("--retries", type=int, default=3)
    parser.add_argument("--retry-base-delay", type=float, default=2.0)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument(
        "--allow-nonformal-counts",
        action="store_true",
        help="Development only: allow an input plan other than the formal 67,320 actions.",
    )
    parser.add_argument("--progress-every", type=int, default=100)
    parser.add_argument(
        "--plan-only",
        action="store_true",
        help="Validate and count all eight input manifests without calling a teacher.",
    )
    args = parser.parse_args(argv)
    if args.input_root is None:
        args.input_root = default_input_root()
    if args.output_root is None:
        args.output_root = default_output_root(args.input_root)
    if args.workers < 1:
        raise ValueError("workers must be at least one")
    if args.max_connections is None:
        args.max_connections = max(100, args.workers)
    if args.max_connections < args.workers:
        raise ValueError("max_connections must be at least workers")
    return args


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if args.plan_only:
        print(json.dumps(plan_dataset(args.input_root), ensure_ascii=False, indent=2, sort_keys=True))
        return 0
    backends = _load_backends(args)
    try:
        summary = annotate_dataset(
            input_root=args.input_root,
            output_root=args.output_root,
            teachers=backends,
            workers=args.workers,
            resume=args.resume,
            enforce_formal_counts=not args.allow_nonformal_counts,
            progress_every=args.progress_every,
        )
    finally:
        for backend in backends.values():
            backend.close()
    print(json.dumps(summary, ensure_ascii=False, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
