def _compact_json(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=False)


def _sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _write_json(path: Path, payload: Mapping[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def _write_json_atomic(path: Path, payload: Mapping[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(f"{path.suffix}.{os.getpid()}.tmp")
    temporary.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    temporary.replace(path)


def _read_jsonl(path: Path) -> list[dict[str, object]]:
    records: list[dict[str, object]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            value = json.loads(line)
            if not isinstance(value, dict):
                raise DatasetContractError(f"{path}:{line_number}: expected a JSON object")
            records.append(value)
    return records


def _normalized_image_path(raw_path: object, *, manifest_path: Path | None = None) -> Path:
    if not isinstance(raw_path, str) or not raw_path.strip():
        raise DatasetContractError("observation is missing a nonempty image path")
    path = Path(raw_path)
    if not path.is_absolute() and manifest_path is not None:
        path = manifest_path.parent / path
    return path.resolve()


def _resolve_image_path(raw_path: object, *, manifest_path: Path | None = None) -> Path:
    path = _normalized_image_path(raw_path, manifest_path=manifest_path)
    if not path.is_file():
        raise FileNotFoundError(str(path))
    return path


def _image_data_url(path: Path) -> str:
    suffix = path.suffix.lower()
    mime = {
        ".png": "image/png",
        ".jpg": "image/jpeg",
        ".jpeg": "image/jpeg",
        ".webp": "image/webp",
    }.get(suffix, "image/png")
    return f"data:{mime};base64,{base64.b64encode(path.read_bytes()).decode('ascii')}"


def _encoded_image(path: Path) -> dict[str, object]:
    return {"type": "image_url", "image_url": {"url": _image_data_url(path)}}


class _RecordImageCache:
    """Keep only one trajectory's image bytes while hashing and encoding it."""

    def __init__(self) -> None:
        self._bytes: dict[Path, bytes] = {}

    def read(self, path: Path) -> bytes:
        if path not in self._bytes:
            self._bytes[path] = path.read_bytes()
        return self._bytes[path]

    def sha256(self, path: Path) -> str:
        return _sha256_bytes(self.read(path))

    def encoded(self, path: Path) -> dict[str, object]:
        suffix = path.suffix.lower()
        mime = {
            ".png": "image/png",
            ".jpg": "image/jpeg",
            ".jpeg": "image/jpeg",
            ".webp": "image/webp",
        }.get(suffix, "image/png")
        data_url = f"data:{mime};base64,{base64.b64encode(self.read(path)).decode('ascii')}"
        return {"type": "image_url", "image_url": {"url": data_url}}


